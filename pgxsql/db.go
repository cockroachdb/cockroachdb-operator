package pgxsql

import (
	"context"
	"database/sql"
	"fmt"
	"net/url"
	"strings"

	"github.com/cockroachdb/errors"
	"github.com/cockroachlabs/cockroach-enterprise-operator/pkg/logging"
	"github.com/jackc/pgx/v4"
	"github.com/jackc/pgx/v4/stdlib"
	"go.uber.org/zap"
)

const CockroachDBSQLPort = 26257

// DB is a handle to a SQL database that manages a pool of zero or more
// underlying connections. In addition to the standard "pgx" driver, it supports
// drivers such as copyist and lintdriver, as long as they're wrapping the "pgx"
// driver. Supporting those drivers requires using the standard sql.Open call,
// which makes it difficult to use PGX configuration like custom network dialers
// (e.g. the K8s PodDialer). To solve these the problems, the DB class wraps
// the Golang sql.DB object and then uses the PGX RegisterConnConfig API to
// set custom configuration.
type DB struct {
	*sql.DB
	connStr string
}

func (d *DB) Close() error {
	if d.DB != nil {
		// Unregister the custom connection configuration before closing the
		// underlying sql.DB.
		stdlib.UnregisterConnConfig(d.connStr)
		return d.DB.Close()
	}
	return nil
}

// Open opens a database specified by the given connection options, and using
// the PGX driver (or a driver that wraps it).
var Open = func(options Options) (*DB, error) {
	pgCfg, err := toPGXConfig(&options)
	if err != nil {
		return nil, errors.Wrap(err, "failed to parse Open options")
	}
	connStr := stdlib.RegisterConnConfig(pgCfg)

	db, err := sql.Open(options.Driver, connStr)
	if err != nil {
		stdlib.UnregisterConnConfig(connStr)
		return nil, err
	}
	return &DB{DB: db, connStr: connStr}, nil
}

// toPGXConfig returns a *pgx.ConnConfig from the given *Options.
func toPGXConfig(options *Options) (*pgx.ConnConfig, error) {
	if options.Driver == "" {
		options.Driver = "pgx"
	}

	// If no host was provided, pgconn ends up using the default value based
	// on the platform the process is running on (e.g. /var/run/postgresql,
	// /private/tmp). Hostnames that begin with / will be treated as unix
	// sockets, and hostname lookups will be skipped for such. When that
	// happens, LookupFunc won't be called. Performing hostname lookups when
	// the hostname is empty was originally a bug, and has been fixed upstream
	// in https://github.com/jackc/pgconn/commit/fb42201c18fcd016c235d4b613f76b2fc1599588.
	// We will pick localhost here so that we always call LookupFunc by default.
	if options.Host == "" {
		options.Host = "localhost"
	}

	if options.Port == 0 {
		options.Port = CockroachDBSQLPort
	}

	// CRDB UA clusters may have the `cluster:` prefix. In such cases, we'll
	// have to check if a default database is provided explicitly.
	if strings.HasPrefix(options.Database, "cluster:") {
		// We can cut the string with '/' as cluster names cannot contain '/'.
		prefix, _, found := strings.Cut(options.Database, "/")
		if !found {
			options.Database = fmt.Sprintf("%s/system", prefix)
		}
	} else if options.Database == "" {
		options.Database = "system"
	}

	if options.LookupFunc == nil {
		options.LookupFunc = IdentityLookup
	}

	query := url.Values{
		"sslmode":         {options.SSLMode()},
		"connect_timeout": {fmt.Sprintf("%.0f", options.OpenTimeout.Seconds())},
	}

	if options.Application != "" {
		query.Set("application_name", options.Application)
	}

	if len(options.OtherOptions) != 0 {
		query.Set("options", strings.Join(options.OtherOptions, " "))
	}

	pgURL := url.URL{
		Scheme:   "postgresql",
		Host:     fmt.Sprintf("%s:%d", options.Host, options.Port),
		Path:     fmt.Sprintf("/%s", options.Database),
		User:     options.User,
		RawQuery: query.Encode(),
	}

	// pgx.Config's must be generated by ParseConfig, otherwise connecting will
	// panic.
	pgCfg, err := pgx.ParseConfig(pgURL.String())
	if err != nil {
		return nil, err
	}
	if options.LookupFunc != nil {
		pgCfg.LookupFunc = options.LookupFunc
	}
	if options.DialFunc != nil {
		pgCfg.DialFunc = options.DialFunc
	}
	pgCfg.Logger = &pgxLogger{}
	pgCfg.LogLevel = pgx.LogLevelWarn
	pgCfg.TLSConfig = options.TLSConfig
	pgCfg.PreferSimpleProtocol = options.PreferSimpleProtocol
	return pgCfg, nil
}

type pgxLogger struct{}

func (*pgxLogger) Log(ctx context.Context, level pgx.LogLevel, msg string, data map[string]any) {
	zapLevel := zap.InfoLevel
	switch level {
	case pgx.LogLevelWarn:
		zapLevel = zap.WarnLevel
	case pgx.LogLevelError:
		zapLevel = zap.ErrorLevel
	case pgx.LogLevelDebug:
		zapLevel = zap.DebugLevel
	case pgx.LogLevelTrace:
		zapLevel = zap.DebugLevel
	}

	zapFields := make([]zap.Field, 0, len(data))

	// Log only the err field to prevent sensitive data from being recorded.
	if value, ok := data["err"]; ok {
		zapFields = append(zapFields, zap.Any("err", value))
	}

	logging.L(ctx).Log(
		zapLevel,
		msg,
		zapFields...)
}

// FakeSigner creates a CertificateSigner that generates real certificates using
// an insecure random number generator and small key sizes.
func FakeSigner() (CertificateSigner, error) {
	randomSource := mathRand.New(mathRand.NewSource(mathRand.Int63()))

	generateKey := func() (*rsa.PrivateKey, error) {
		return rsa.GenerateKey(randomSource, 1024)
	}

	signer, err := newFakeSigner(time.Now, generateKey, randomSource)
	if err != nil {
		return nil, err
	}
	return signer, nil
}

// DeterministicFakeSigner creates a CertificateSigner that deterministically
// generates certificates. This is useful for dev environment where we
// can reliably get the same certs without using an external certificate
// authority.
func DeterministicFakeSigner() (CertificateSigner, error) {
	randomNumber := int64(2804583565434572800) /* chosen by a a fair dice roll */
	now := time.Date(2001, 2, 3, 4, 5, 6, 7, time.UTC)

	return newFakeSigner(func() time.Time { return now }, deterministicKeyGenerator(),
		mathRand.New(mathRand.NewSource(randomNumber)))
}

// DeterministicFakeSignerForTesting creates a CertificateSigner that deterministically
// generates certificates. This is useful for tests that use kuberecord or write
// the certificates to golden files. Prefer to use FakeSigner as its behavior
// is closer to a real signer.
func DeterministicFakeSignerForTesting(t *testing.T) CertificateSigner {
	signer, err := DeterministicFakeSigner()
	require.NoError(t, err)
	return signer
}

// deterministicKeys contains 100 randomly generated RSA keys. They are used by
// the DeterministicFakeSigner to produce deterministic certificates. Go
// randomizes secret key generation even if the supplied random number generator
// is deterministic. If the returned function is called more than 100 times, we
// rollover and reuse keys.
//
// The deterministic_keys.pem file was generated by running the following command:
// for i in {1..100}; do openssl genrsa 1024 >> deterministic_keys.pem; done
//
//go:embed deterministic_keys.pem
var deterministicKeys []byte

func deterministicKeyGenerator() func() (*rsa.PrivateKey, error) {
	var keys []*rsa.PrivateKey
	var i atomic.Int64
	for der, rest := pem.Decode(deterministicKeys); der != nil; der, rest = pem.Decode(rest) {
		if der.Type != "RSA PRIVATE KEY" {
			log.Fatalf("unexpected pem object %s in deterministicKeys", der.Type)
		}
		key, err := x509.ParsePKCS1PrivateKey(der.Bytes)
		if err != nil {
			log.Fatalf("invalid key in deterministicKeys: %v", err)
		}
		keys = append(keys, key)
	}
	if len(keys) != 100 {
		log.Fatalf("expected to find 100 keys in deterministic_keys.pem found %d", len(keys))
	}
	return func() (*rsa.PrivateKey, error) {
		key := keys[i.Load()%100]
		i.Add(1)
		return key, nil
	}
}

// newFakeSigner constructs a CA using the provided key generator and random
// reader. Calls to keyGenerator and randomReader are wrapped in a mutex since
// the go random number generators are not thread safe.
func newFakeSigner(
	clock func() time.Time, keyGenerator func() (*rsa.PrivateKey, error), randomReader io.Reader,
) (CertificateSigner, error) {
	fc := &fakeCA{serialNumber: 1}
	fc.mu.random = randomReader
	fc.mu.keyGenerator = keyGenerator

	fc.caCert = &x509.Certificate{
		SerialNumber: big.NewInt(1),
		Subject: pkix.Name{
			Organization: []string{"Cockroach Test CA"},
		},
		NotBefore: clock(),
		// If you are looking at this line in the year 2101: I'm sorry for breaking CI.
		NotAfter:              clock().AddDate(100, 0, 0),
		IsCA:                  true,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth, x509.ExtKeyUsageServerAuth},
		KeyUsage:              x509.KeyUsageDigitalSignature | x509.KeyUsageCertSign,
		BasicConstraintsValid: true,
	}
	fc.serialNumber++

	var err error
	fc.caPrivKey, err = keyGenerator()
	if err != nil {
		return nil, err
	}

	caPrivKeyPEM := new(bytes.Buffer)
	if err := pem.Encode(caPrivKeyPEM, &pem.Block{
		Type:  "RSA PRIVATE KEY",
		Bytes: x509.MarshalPKCS1PrivateKey(fc.caPrivKey),
	}); err != nil {
		return nil, err
	}
	fc.caPublicKeyPEM = caPrivKeyPEM.Bytes()

	caBytes, err := x509.CreateCertificate(randomReader, fc.caCert, fc.caCert, &fc.caPrivKey.PublicKey, fc.caPrivKey)
	if err != nil {
		return nil, err
	}
	caPEM := new(bytes.Buffer)
	if err := pem.Encode(caPEM, &pem.Block{
		Type:  "CERTIFICATE",
		Bytes: caBytes,
	}); err != nil {
		return nil, err
	}
	fc.caPublicKeyPEM = caPEM.Bytes()

	return fc, nil
}

type fakeCA struct {
	serialNumber   int
	caCert         *x509.Certificate
	caPrivKey      *rsa.PrivateKey
	caPublicKeyPEM []byte
	mu             struct {
		sync.Mutex
		random       io.Reader
		keyGenerator func() (*rsa.PrivateKey, error)
	}
}

func (fc *fakeCA) Certificate(ctx context.Context) ([]byte, error) {
	return fc.caPublicKeyPEM, nil
}

func (fc *fakeCA) Sign(ctx context.Context, csr CertificateSigningRequest) (*Bundle, error) {
	fc.serialNumber++

	// Parse the string URIs into golang url.URLs
	var err error
	parsedURIs := make([]*url.URL, len(csr.URINames))
	for i, uri := range csr.URINames {
		if parsedURIs[i], err = url.Parse(uri); err != nil {
			return nil, err
		}
	}

	// Parse the string IPs into net.IPs
	parsedIP := make([]net.IP, len(csr.IPAddresses))
	for i, ip := range csr.IPAddresses {
		if parsedIP[i] = net.ParseIP(ip); parsedIP[i] == nil {
			return nil, errors.Newf("%s is an invalid IP address", ip)
		}
	}

	// Generate and PEM encode the certificate's private key.
	fc.mu.Lock()
	defer fc.mu.Unlock()
	certPrivKey, err := fc.mu.keyGenerator()
	if err != nil {
		return nil, err
	}
	certPrivKeyBytes := new(bytes.Buffer)
	if err := pem.Encode(certPrivKeyBytes, &pem.Block{
		Type:  "RSA PRIVATE KEY",
		Bytes: x509.MarshalPKCS1PrivateKey(certPrivKey),
	}); err != nil {
		return nil, err
	}

	notAfter := fc.caCert.NotAfter
	if csr.TTL != 0 {
		notAfter = timeutils.Now().Add(csr.TTL)
	}

	// Create, sign, and PEM encode the certificate.
	cert := &x509.Certificate{
		SerialNumber: big.NewInt(int64(fc.serialNumber)),
		NotBefore:    fc.caCert.NotBefore,
		NotAfter:     notAfter,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth, x509.ExtKeyUsageServerAuth},
		KeyUsage:     x509.KeyUsageDigitalSignature,
		DNSNames:     csr.DNSNames,
		URIs:         parsedURIs,
		IPAddresses:  parsedIP,
		Subject: pkix.Name{
			CommonName:         csr.CommonName,
			OrganizationalUnit: csr.OrganizationalUnit,
		},
	}
	certBytes, err := x509.CreateCertificate(fc.mu.random, cert, fc.caCert, &certPrivKey.PublicKey, fc.caPrivKey)
	if err != nil {
		return nil, err
	}
	certPEM := new(bytes.Buffer)
	if err := pem.Encode(certPEM, &pem.Block{
		Type:  "CERTIFICATE",
		Bytes: certBytes,
	}); err != nil {
		return nil, err
	}

	return &Bundle{
		Certificate: certPEM.Bytes(),
		PrivateKey:  certPrivKeyBytes.Bytes(),
	}, nil
}

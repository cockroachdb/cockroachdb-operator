package kubeconfig

import (
	"sync"

	"github.com/cockroachlabs/cockroach-enterprise-operator/kube"
	"github.com/cockroachlabs/cockroach-enterprise-operator/kube/kubetest"
	"k8s.io/client-go/rest"
)

var fakeCtls struct {
	sync.Mutex
	ctls map[string]*kube.Ctl
}

// TODO(CC-24774): Add functionality to modify reactors post-instantiation.
var FakeCtlOptions = kubetest.Options{
	AdvancedEmulation: true,
	Options: kube.Options{
		BeforeMutation: kubetest.MakeQuiescent,
	},
}

// getFakeCtl gets or creates a persistent [kube.Ctl] with AdvancedEmulation
// enabled. This functionality should only be leveraged in test cases.
func getFakeCtl(cfg *rest.Config) *kube.Ctl {
	fakeCtls.Lock()
	defer fakeCtls.Unlock()

	if fakeCtls.ctls == nil {
		fakeCtls.ctls = make(map[string]*kube.Ctl)
	}

	// Use .CAData as our map key. See [cloudinfra.FakeCloud] for details.
	key := string(cfg.CAData)

	if ctl, ok := fakeCtls.ctls[key]; ok {
		return ctl
	}

	fakeCtls.ctls[key] = kubetest.NewFakeCtl(FakeCtlOptions)

	return fakeCtls.ctls[key]
}

// isFake returns true if the given [rest.Config] was generated by
// [cloudinfra.FakeCloud].
func isFake(cfg *rest.Config) bool {
	return cfg.Host == "FAKEAPISERVER"
}

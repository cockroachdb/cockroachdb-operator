package kube

import (
	"github.com/cockroachdb/errors"
	"k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"
	"k8s.io/apimachinery/pkg/runtime"
)

const (
	deploymentRevisionAnnotation            = "deployment.kubernetes.io/revision"
	deprecatedDaemonsetGenerationAnnotation = "deprecated.daemonset.template.generation"
)

var ignoreFields = [][]string{
	{"status"},
	{"metadata", "selfLink"},
	{"metadata", "uid"},
	{"metadata", "resourceVersion"},
	{"metadata", "generation"},
	{"metadata", "creationTimestamp"},
	{"metadata", "deletionTimestamp"},
	{"metadata", "annotations", deploymentRevisionAnnotation},
	{"metadata", "annotations", deprecatedDaemonsetGenerationAnnotation},
	{"metadata", "annotations", restartedAtAnnotation},
	{"metadata", "managedFields"},
}

// marshalObject is a specialized version of JSON.Marshal. It removes any
// fields that have been generated by the server or should be ignored by
// clients (Status, UID, etc).
func marshalObject(obj Object) ([]byte, error) {
	// Convert to Unstructured which allows us to easily prune fields.
	unstruct, err := convertToUnstructured(obj)
	if err != nil {
		return nil, errors.Wrap(err, "unable to convert object to unstructured")
	}
	for _, field := range ignoreFields {
		unstructured.RemoveNestedField(unstruct.Object, field...)
	}
	return runtime.Encode(unstructured.UnstructuredJSONScheme, unstruct)
}
